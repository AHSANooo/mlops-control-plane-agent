"""Pydantic V2 Schemas for MLOps AI Agent tools, requests, responses, and evidence."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from pydantic import BaseModel, Field


class ToolResult(BaseModel):
    """Standardized result returned by every agent tool."""

    success: bool = Field(..., description="True if operation completed without unhandled errors")
    tool_name: str = Field(..., description="Name of the executing tool")
    data: Any = Field(default=None, description="Structured payload or payload dictionary")
    error: str | None = Field(default=None, description="Error message if execution failed")
    duration_ms: float = Field(default=0.0, description="Execution duration in milliseconds")


class EvidenceItem(BaseModel):
    """A grounded piece of operational evidence collected from infrastructure tools."""

    source: str = Field(..., description="Tool or subsystem source (e.g. DVC, MLflow, Airflow, K8s)")
    summary: str = Field(..., description="Concise summary of the verified fact")
    details: Any = Field(default=None, description="Underlying telemetry or record details")
    timestamp: str = Field(
        default_factory=lambda: datetime.now(UTC).isoformat(),
        description="ISO 8601 observation timestamp",
    )


class AgentChatRequest(BaseModel):
    """Incoming user request schema for agent interaction."""

    message: str = Field(..., min_length=1, description="Natural-language prompt or command")
    conversation_history: list[dict[str, str]] = Field(
        default_factory=list,
        description="Optional prior chat turns [{'role': 'user'|'assistant', 'content': '...'}]",
    )
    user_confirmed: bool = Field(
        default=False,
        description="Explicit user confirmation required for any cluster mutation or DAG trigger",
    )
    request_id: str | None = Field(
        default=None,
        description="Optional correlation request ID for telemetry tracing",
    )


class AgentChatResponse(BaseModel):
    """Evidence-based response generated by the MLOps agent orchestrator."""

    reply: str = Field(..., description="Comprehensive natural-language answer")
    known_facts: list[str] = Field(
        default_factory=list,
        description="Verified facts supported by real tool outputs",
    )
    uncertainties: list[str] = Field(
        default_factory=list,
        description="Missing, unconfirmed, or unreachable parameters",
    )
    recommended_actions: list[str] = Field(
        default_factory=list,
        description="Suggested operational steps without auto-executing mutations",
    )
    tools_executed: list[ToolResult] = Field(
        default_factory=list,
        description="List of tool results executed during request processing",
    )
    evidence: list[EvidenceItem] = Field(
        default_factory=list,
        description="Grounded evidence items supporting the response",
    )
    request_id: str = Field(..., description="Correlation request ID for audit and tracing")


# Tool Input Schemas (Strict Pydantic V2)
class DvcVersionInput(BaseModel):
    version_or_tag: str = Field(default="HEAD", description="Git tag or commit reference")


class DvcDiffInput(BaseModel):
    target_a: str = Field(default="v1.0", description="First git reference")
    target_b: str = Field(default="v2.0", description="Second git reference")


class MlflowRunQueryInput(BaseModel):
    experiment_name: str = Field(default="customer-churn-prediction")
    max_runs: int = Field(default=5, ge=1, le=50)


class MlflowBestRunInput(BaseModel):
    experiment_name: str = Field(default="customer-churn-prediction")
    metric_name: str = Field(default="f1_score")


class AirflowTriggerInput(BaseModel):
    dag_id: str = Field(default="churn_model_training_pipeline")
    user_confirmed: bool = Field(default=False)
    conf: dict[str, Any] | None = Field(default=None)


class AirflowDagRunInput(BaseModel):
    dag_id: str = Field(default="churn_model_training_pipeline")
    limit: int = Field(default=5, ge=1, le=50)


class AirflowTaskLogsInput(BaseModel):
    dag_id: str = Field(default="churn_model_training_pipeline")
    dag_run_id: str = Field(...)
    task_id: str = Field(...)


class K8sNamespaceInput(BaseModel):
    namespace: str = Field(default="mlops-prod")


class K8sRestartInput(BaseModel):
    deployment_name: str = Field(default="model-inference")
    namespace: str = Field(default="mlops-prod")
    user_confirmed: bool = Field(default=False)


class K8sLogsInput(BaseModel):
    pod_name: str = Field(...)
    namespace: str = Field(default="mlops-prod")
    tail_lines: int = Field(default=50, ge=1, le=500)
